#!/usr/bin/env python3
"""Bake a 24-frame spinning ring into an EDK II RGBA sprite header.

Frames are stored sparsely: transparent pixels are omitted, and every
remaining pixel keeps its own 8-bit alpha. The loader restores a saved GOP
rectangle before blending one frame, so the firmware logo/background stays
untouched.

Usage: python3 tools/splash/mkspinner.py [output header]
"""

import math
import os
import sys

FRAMES = 24
SIZE = 96
SCALE = 4
RADIUS = 36
TAIL_DEG = 120
R, G, B = 0xFF, 0x93, 0x2C


def main():
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        sys.exit("mkspinner: Pillow is required (pip install Pillow)")

    root = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "edk2", "NovusSplash", "SpinnerFrames.h")

    big = SIZE * SCALE
    c = big / 2.0
    r = RADIUS * SCALE
    frames = []

    for frame in range(FRAMES):
        img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)
        head = frame * 360.0 / FRAMES

        # Soft outer glow first, then the opaque ring on top.
        for step in range(24, -1, -1):
            delta = step * TAIL_DEG / 24.0
            alpha = int(255 * (1.0 - step / 25.0))
            a0 = head - delta - 4.0
            a1 = head - delta + 4.0
            draw.arc((c - r - 5, c - r - 5, c + r + 5, c + r + 5),
                     start=a0, end=a1, fill=(R, G, B, alpha // 3),
                     width=int(7 * SCALE))
        for step in range(24, -1, -1):
            delta = step * TAIL_DEG / 24.0
            alpha = int(255 * (1.0 - step / 25.0))
            a0 = head - delta - 2.0
            a1 = head - delta + 2.0
            draw.arc((c - r, c - r, c + r, c + r),
                     start=a0, end=a1, fill=(R, G, B, alpha),
                     width=int(3 * SCALE))

        img = img.resize((SIZE, SIZE), Image.LANCZOS)
        pixels = []
        for y in range(SIZE):
            for x in range(SIZE):
                r8, g8, b8, a8 = img.getpixel((x, y))
                if a8 >= 8:
                    pixels.append((x, y, b8, g8, r8, a8))
        frames.append(pixels)

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + ".tmp"
    with open(tmp, "w") as out:
        out.write("/* Generated by tools/splash/mkspinner.py - do not edit.\n")
        out.write(" * Sparse RGBA frames: {X,Y,{Blue,Green,Red,Alpha}}.\n")
        out.write(" */\n")
        out.write("#ifndef NOVUS_EFI_SPINNER_FRAMES_H\n")
        out.write("#define NOVUS_EFI_SPINNER_FRAMES_H\n\n")
        out.write("#define NOVUS_SPINNER_FRAMES %d\n" % FRAMES)
        out.write("#define NOVUS_SPINNER_W     %d\n" % SIZE)
        out.write("#define NOVUS_SPINNER_H     %d\n\n" % SIZE)
        for i, pixels in enumerate(frames):
            out.write("STATIC CONST NOVUS_SPRITE_PIXEL mNovusSpinner%d[] = {\n" % i)
            for x, y, b8, g8, r8, a8 in pixels:
                out.write("    {%d,%d,{%d,%d,%d,%d}},\n" % (x, y, b8, g8, r8, a8))
            out.write("};\n\n")
        out.write("STATIC CONST NOVUS_SPRITE_FRAME mNovusSpinnerFrames[%d] = {\n" % FRAMES)
        for i, pixels in enumerate(frames):
            out.write("    {mNovusSpinner%d, %d},\n" % (i, len(pixels)))
        out.write("};\n\n#endif /* NOVUS_EFI_SPINNER_FRAMES_H */\n")
    os.replace(tmp, dst)
    total = sum(len(f) for f in frames)
    print("spinner: %d frames %dx%d, %d pixels -> %s (%d bytes)" % (
        FRAMES, SIZE, SIZE, total, dst, os.path.getsize(dst)))


if __name__ == "__main__":
    main()
