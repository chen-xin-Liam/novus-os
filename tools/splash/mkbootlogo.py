#!/usr/bin/env python3
"""Generate a C pixel blob for the boot logo.

The boot splash runs before the heap and before any image decoder is
available, so boot.png is converted here into a plain 0xAARRGGBB array that
nd_boot.c can blit with nd_blit(). Regenerated by the Makefile whenever the
PNG changes.

Usage: python3 tools/splash/mkbootlogo.py [output header]
"""

import os
import sys

WIDTH = 320


def main():
    try:
        from PIL import Image
    except ImportError:
        sys.exit("mkbootlogo: Pillow is required (pip install Pillow)")

    root = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    src = os.path.join(root, "assets", "splash", "boot.png")
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "build", "boot_logo.h")

    with Image.open(src) as image:
        image = image.convert("RGBA")
        w, h = image.size
        height = max(1, round(h * WIDTH / float(w)))
        image = image.resize((WIDTH, height), Image.LANCZOS)
        # The artwork is opaque; flatten any stray alpha onto white so the
        # blob has no transparent pixels (nd_blit is an opaque copy).
        flat = Image.new("RGBA", image.size, (255, 255, 255, 255))
        flat.alpha_composite(image)
        px = list(flat.getdata())

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + ".tmp"
    with open(tmp, "w") as out:
        out.write("/* Generated from assets/splash/boot.png - do not edit. */\n")
        out.write("#ifndef NOVUS_BOOT_LOGO_H\n#define NOVUS_BOOT_LOGO_H\n")
        out.write("#define BOOT_LOGO_W %d\n" % WIDTH)
        out.write("#define BOOT_LOGO_H %d\n" % height)
        out.write("static const UINT32 g_boot_logo[BOOT_LOGO_W * BOOT_LOGO_H] = {\n")
        for i in range(0, len(px), 8):
            words = []
            for r, g, b, a in px[i:i + 8]:
                words.append("0x%08Xu" % ((a << 24) | (r << 16) | (g << 8) | b))
            out.write("    " + ", ".join(words) + ",\n")
        out.write("};\n#endif\n")
    os.replace(tmp, dst)
    print("boot logo: %dx%d -> %s (%d bytes)" % (
        WIDTH, height, dst, os.path.getsize(dst)))


if __name__ == "__main__":
    main()
