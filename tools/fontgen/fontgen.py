#!/usr/bin/env python3
"""Novus OS - CJK bitmap font generator.

Renders the characters this OS actually shows into 16x16 1bpp glyphs and
writes graphics/nd_font_cjk.c. The output is committed: the build must not
depend on a host font, and the glyph set has to be reviewable as text.

The character set is the union of

  * every character in tools/fontgen/charset.txt (the UI corpus, one string
    per line - keep it in sync with the strings in the sources), and
  * every character the IME can produce (tools/imegen/pinyin.txt).

Usage:
    python3 tools/fontgen/fontgen.py            # regenerate the C file
    python3 tools/fontgen/fontgen.py --preview 中文   # ASCII art, for eyeballing
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CHARSET = os.path.join(HERE, "charset.txt")
PINYIN = os.path.join(ROOT, "tools", "imegen", "pinyin.txt")
OUT_C = os.path.join(ROOT, "graphics", "nd_font_cjk.c")

FONT_CANDIDATES = [
    ("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc", 2),  # SC
    ("/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc", 2),
    ("/usr/share/fonts/truetype/arphic/uming.ttc", 0),
]

GLYPH = 16      # ink box, also the advance


def pick_font():
    for path, index in FONT_CANDIDATES:
        if os.path.exists(path):
            return ImageFont.truetype(path, GLYPH, index=index)
    sys.exit("no CJK font found; install fonts-noto-cjk")


def render(font, ch):
    """One 16x16 glyph: a list of 16 rows, MSB = leftmost column."""
    img = Image.new("L", (GLYPH, GLYPH), 0)
    ImageDraw.Draw(img).text((GLYPH // 2, GLYPH // 2), ch, font=font,
                             fill=255, anchor="mm")
    px = img.load()
    rows = []
    for y in range(GLYPH):
        bits = 0
        for x in range(GLYPH):
            if px[x, y] >= 96:
                bits |= 1 << (GLYPH - 1 - x)
        rows.append(bits)
    return rows


def preview(chars):
    font = pick_font()
    for ch in chars:
        rows = render(font, ch)
        print(f"--- {ch} U+{ord(ch):04X}")
        for bits in rows:
            print("".join("#" if bits & (1 << (GLYPH - 1 - x)) else "."
                          for x in range(GLYPH)))


SOURCES = ["graphics", "wm/novus-wm", "apps/src", "kernel", "tools/langgen"]


def scan_sources(chars):
    """Every non-ASCII character the UI can display. Scanning the sources
    rather than hand-maintaining a list is what keeps the glyph set in step
    with the strings: a new Chinese label is one regeneration away."""
    for root in SOURCES:
        for dirpath, _, files in os.walk(os.path.join(ROOT, root)):
            for f in files:
                if not (f.endswith(".c") or f.endswith(".h") or
                        f.endswith(".rs") or f.endswith(".toml")):
                    continue
                try:
                    text = open(os.path.join(dirpath, f), encoding="utf-8",
                                errors="ignore").read()
                except OSError:
                    continue
                chars.update(c for c in text if ord(c) > 0x7F)


def corpus_chars():
    chars = set()
    for line in open(CHARSET, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        chars.update(c for c in line if ord(c) > 0x7F)
    scan_sources(chars)
    for line in open(PINYIN, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        chars.update(c for c in line.split("\t")[1] if ord(c) > 0x7F)
    return sorted(chars, key=ord)


def gen():
    chars = corpus_chars()
    font = pick_font()
    out = []
    out.append("/**")
    out.append(" * Novus OS - CJK glyphs (generated, do not edit).")
    out.append(" *")
    out.append(" * 16x16 1bpp, MSB = leftmost column, row-major, two bytes a row.")
    out.append(" * Codepoints ascend, so lookup is a binary search.")
    out.append(" * Generated by tools/fontgen/fontgen.py from Noto Sans CJK SC.")
    out.append(" */")
    out.append("")
    out.append('#include "nd_internal.h"')
    out.append('#include "nd_font_cjk.h"')
    out.append("")
    out.append(f"const UINT16 g_cjk_count = {len(chars)}u;")
    out.append("")
    out.append("const UINT16 g_cjk_cp[] = {")
    for i in range(0, len(chars), 12):
        out.append("    " + ", ".join(f"0x{ord(c):04X}" for c in chars[i:i + 12]) + ",")
    out.append("};")
    out.append("")
    out.append("const UINT16 g_cjk_bits[] = {")
    for c in chars:
        rows = render(font, c)
        out.append("    " + ", ".join(f"0x{b:04X}" for b in rows) + f", /* {c} */")
    out.append("};")
    out.append("")

    with open(OUT_C, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    size = len(chars) * (GLYPH * 2 + 2)
    print(f"fontgen: wrote {OUT_C}: {len(chars)} glyphs, ~{size // 1024} KiB")


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
    else:
        gen()


main()
