#!/usr/bin/env python3
"""Extract the UI's emergency glyph subset from the committed Unifont data."""

from __future__ import annotations

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]


def generate(output: Path) -> None:
    index = (ROOT / "graphics" / "nd_font_uni.c").read_text(encoding="utf-8")

    def array(name: str) -> list[int]:
        match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", index, re.S)
        if match is None:
            raise ValueError(f"font index missing {name}")
        return [int(value, 0) for value in re.findall(r"0x[0-9A-Fa-f]+|\d+", match[1])]

    pages = array("g_uni_page")
    bases = array("g_uni_base")
    valid = array("g_uni_valid")
    wide = array("g_uni_wide")
    blob = (ROOT / "graphics" / "nd_font_data.bin").read_bytes()
    sources = [
        *sorted((ROOT / "graphics").glob("*.c")),
        *sorted((ROOT / "kernel").glob("*.c")),
        *sorted((ROOT / "wm").rglob("*.c")),
        *sorted((ROOT / "apps" / "src").rglob("*.rs")),
    ]
    chars = sorted({ord(ch) for path in sources
                    for ch in path.read_text(encoding="utf-8") if ord(ch) >= 128})
    lines = [
        "/* Generated by tools/fontgen/fallback.py from the committed GNU",
        " * Unifont data (GPLv2+ with font embedding exception). */",
        f"#define ND_FONT_DATA_SIZE {len(blob)}u",
        "static const struct { UINT32 cp; UINT8 wide; UINT8 bits[32]; }",
        "g_fallback_font[] = {",
    ]
    for cp in chars:
        slot = pages[cp >> 8]
        if slot == 0xFFFF:
            continue
        low = cp & 255
        bitmap = valid[slot * 32:slot * 32 + 32]
        if not bitmap[low >> 3] & (1 << (low & 7)):
            continue
        rank = sum(bin(value).count("1") for value in bitmap[:low >> 3])
        rank += bin(bitmap[low >> 3] & ((1 << (low & 7)) - 1)).count("1")
        offset = (bases[slot] + rank) * 32
        glyph = blob[offset:offset + 32]
        if len(glyph) != 32:
            raise ValueError(f"truncated glyph U+{cp:04X}")
        advance = 16 if wide[slot * 32 + (low >> 3)] & (1 << (low & 7)) else 8
        bits = ", ".join(f"0x{value:02X}" for value in glyph)
        lines.append(f"  {{0x{cp:X}u, {advance}, {{{bits}}}}},")
    lines.append("};\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="ascii")
    print(f"font fallback: {len(lines) - 6} UI glyphs")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    generate(parser.parse_args().output)
