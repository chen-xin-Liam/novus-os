#!/usr/bin/env python3
"""Novus OS - generate the design-token sources from theme.toml.

Two consumers share one palette: the kernel graphics stack (C) and the
ring-3 applications (Rust). Both files are generated and committed, so a
normal build never needs Python - the same rule the CJK font and the IME
dictionary follow.

Usage:
    python3 tools/themegen/themegen.py            # write the generated files
    python3 tools/themegen/themegen.py --check    # non-zero when stale
"""

import io
import os
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SOURCE = os.path.join(HERE, "theme.toml")
OUT_C_H = os.path.join(ROOT, "graphics", "nd_theme.h")
OUT_C_C = os.path.join(ROOT, "graphics", "nd_theme.c")
OUT_RS = os.path.join(ROOT, "apps", "src", "theme.rs")

ROLES = [
    "canvas_top",
    "canvas_bottom",
    "surface",
    "card",
    "subtle",
    "stroke",
    "text",
    "dim",
    "accent",
    "on_accent",
    "success",
    "warn",
    "danger",
    "selection",
    "shadow",
]

METRICS = [
    "radius_control",
    "radius_card",
    "radius_pill",
    "space_xs",
    "space_s",
    "space_m",
    "space_l",
    "space_xl",
    "control_h",
    "button_h",
    "row_h",
    "title_h",
    "shadow_spread",
]

BANNER = "/* Generated by tools/themegen/themegen.py from theme.toml - do not edit. */\n"


def hex_to_rgb(value):
    text = value.strip()
    if not text.startswith("#") or len(text) != 7:
        raise ValueError("bad colour %r (want #RRGGBB)" % value)
    return int(text[1:3], 16), int(text[3:5], 16), int(text[5:7], 16)


def rgb_argb(value):
    r, g, b = hex_to_rgb(value)
    return (0xFF << 24) | (r << 16) | (g << 8) | b


def c_hex(value):
    return "0x%08Xu" % rgb_argb(value)


def rust_hex(value):
    return "0x00%02X%02X%02X" % hex_to_rgb(value)


def gen_header(doc):
    out = io.StringIO()
    out.write("/**\n * Novus OS - semantic design tokens (Novus Fluent).\n *\n"
              " * " + BANNER.strip("/*/\n ") + "\n"
              " * Roles are resolved at paint time from the current light/dark\n"
              " * palette, so the shell, the window manager and the installer all\n"
              " * change together instead of each keeping a copy of the colours.\n */\n\n")
    out.write("#ifndef NOVUS_ND_THEME_H\n#define NOVUS_ND_THEME_H\n\n#include \"uefi.h\"\n\n")
    out.write("#define ND_THEME_TOKEN_VERSION 0x00010000u\n\n")
    out.write("typedef enum {\n  ND_THEME_LIGHT = 0,\n  ND_THEME_DARK = 1,\n  ND_THEME_AUTO = 2\n} nd_theme_mode_t;\n\n")
    out.write("typedef struct {\n")
    for role in ROLES:
        out.write("  UINT32 %s;\n" % role)
    out.write("} nd_tokens_t;\n\n")
    out.write("typedef struct {\n")
    for m in METRICS:
        out.write("  INT32 %s;\n" % m)
    out.write("} nd_metrics_t;\n\n")
    out.write("/* Current palette (auto already resolved), metrics, and runtime state. */\n")
    out.write("const nd_tokens_t  *nd_tokens(void);\n")
    out.write("const nd_metrics_t *nd_metrics(void);\n")
    out.write("const nd_tokens_t  *nd_tokens_for(int dark);\n\n")
    out.write("nd_theme_mode_t nd_theme_mode(void);\n")
    out.write("int             nd_theme_is_dark(void);\n")
    out.write("void            nd_theme_set_mode(nd_theme_mode_t mode);\n")
    out.write("UINT32          nd_theme_version(void);\n")
    out.write("/* Re-evaluate auto mode (RTC hour). Returns 1 when it changed. */\n")
    out.write("int             nd_theme_resolve(void);\n\n")
    out.write("UINT32 nd_theme_accent(void);\n")
    out.write("/* Top colour of wallpaper `index` in the current mode, for pickers. */\n")
    out.write("UINT32 nd_theme_paper_top(UINT32 index);\n")
    out.write("void   nd_theme_set_accent(UINT32 rgb);\n")
    out.write("UINT32 nd_theme_wallpaper(void);\n")
    out.write("void   nd_theme_set_wallpaper(UINT32 index);\n")
    out.write("int    nd_theme_wallpaper_count(void);\n\n")
    out.write("#endif /* NOVUS_ND_THEME_H */\n")
    return out.getvalue()


def gen_c(doc):
    metrics = doc["metrics"]
    out = io.StringIO()
    out.write("/**\n * Novus OS - design token tables (generated).\n */\n\n")
    out.write("#include \"kernel.h\"\n#include \"nd_theme.h\"\n#include \"rtc.h\"\n\n")
    out.write("static const nd_tokens_t g_light = {\n")
    for role in ROLES:
        out.write("    %s, /* %s */\n" % (c_hex(doc["light"][role]), role))
    out.write("};\n\n")
    out.write("static const nd_tokens_t g_dark = {\n")
    for role in ROLES:
        out.write("    %s, /* %s */\n" % (c_hex(doc["dark"][role]), role))
    out.write("};\n\n")
    out.write("static const nd_metrics_t g_metrics = {\n")
    for m in METRICS:
        out.write("    %d, /* %s */\n" % (int(metrics[m]), m))
    out.write("};\n\n")
    for name, mode in (("g_light_papers", "light"), ("g_dark_papers", "dark")):
        papers = doc[mode]["wallpapers"]
        out.write("static const UINT32 %s[][2] = {\n" % name)
        for paper in papers:
            out.write("    {%s, %s},\n" % (c_hex(paper["top"]), c_hex(paper["bottom"])))
        out.write("};\n\n")
    out.write("static nd_theme_mode_t g_mode = ND_THEME_AUTO;\n")
    out.write("static int             g_is_dark;\n")
    out.write("static UINT32          g_version = 1u;\n")
    out.write("static UINT32          g_accent;    /* 0 = palette accent */\n")
    out.write("static UINT32          g_wallpaper;\n")
    out.write("static nd_tokens_t     g_current;\n")
    out.write("static int             g_built;   /* g_current holds a resolved palette */\n\n")
    out.write("static void theme_build(void) {\n")
    out.write("  const nd_tokens_t *base = g_is_dark ? &g_dark : &g_light;\n")
    out.write("  const UINT32 (*papers)[2] = g_is_dark ? g_dark_papers : g_light_papers;\n")
    out.write("  UINT32 count = (UINT32)(sizeof(g_light_papers) / sizeof(g_light_papers[0]));\n")
    out.write("  UINT32 idx = (g_wallpaper < count) ? g_wallpaper : 0u;\n\n")
    out.write("  g_current = *base;\n")
    out.write("  g_current.canvas_top = papers[idx][0];\n")
    out.write("  g_current.canvas_bottom = papers[idx][1];\n")
    out.write("  if (g_accent != 0u) {\n")
    out.write("    /* Readable caption on a user accent: luminance picks the ink. */\n")
    out.write("    UINT32 r = (g_accent >> 16) & 0xFFu;\n")
    out.write("    UINT32 g = (g_accent >> 8) & 0xFFu;\n")
    out.write("    UINT32 b = g_accent & 0xFFu;\n")
    out.write("    UINT32 luma = (r * 299u + g * 587u + b * 114u) / 1000u;\n\n")
    out.write("    g_current.accent = g_accent;\n")
    out.write("    g_current.on_accent = (luma >= 150u) ? 0x00002436u : 0x00FFFFFFu;\n")
    out.write("  }\n")
    out.write("}\n\n")
    out.write("static void theme_apply(void);\n\n")
    out.write("const nd_metrics_t *nd_metrics(void) { return &g_metrics; }\n")
    out.write("const nd_tokens_t *nd_tokens_for(int dark) { return dark ? &g_dark : &g_light; }\n")
    out.write("const nd_tokens_t *nd_tokens(void) {\n"
              "  /* First use may precede any mode change (light mode at boot used\n"
              "   * to leave the table zeroed, which painted a black desktop). */\n"
              "  if (!g_built) {\n    theme_apply();\n  }\n"
              "  return &g_current;\n}\n")
    out.write("nd_theme_mode_t nd_theme_mode(void) { return g_mode; }\n")
    out.write("int nd_theme_is_dark(void) { return g_is_dark; }\n")
    out.write("UINT32 nd_theme_version(void) { return g_version; }\n\n")
    out.write("static void theme_apply(void) {\n  theme_build();\n  g_built = 1;\n  g_version++;\n}\n\n")
    out.write("int nd_theme_resolve(void) {\n")
    out.write("  UINT8 hour = 0;\n  UINT8 minute = 0;\n  int want;\n\n")
    out.write("  if (g_mode != ND_THEME_AUTO) {\n    return 0;\n  }\n")
    out.write("  if (!rtc_now(&hour, &minute)) {\n    return 0; /* no RTC: keep the last resolution */\n  }\n")
    out.write("  want = (hour < 7u || hour >= 19u) ? 1 : 0;\n")
    out.write("  if (want == g_is_dark) {\n    return 0;\n  }\n")
    out.write("  g_is_dark = want;\n  theme_apply();\n  return 1;\n}\n\n")
    out.write("void nd_theme_set_mode(nd_theme_mode_t mode) {\n")
    out.write("  if (mode > ND_THEME_AUTO) {\n    return;\n  }\n")
    out.write("  g_mode = mode;\n")
    out.write("  if (mode == ND_THEME_AUTO) {\n")
    out.write("    UINT8 hour = 0;\n    UINT8 minute = 0;\n\n")
    out.write("    g_is_dark = rtc_now(&hour, &minute) ? ((hour < 7u || hour >= 19u) ? 1 : 0) : g_is_dark;\n")
    out.write("  } else {\n    g_is_dark = (mode == ND_THEME_DARK) ? 1 : 0;\n  }\n")
    out.write("  theme_apply();\n}\n\n")
    out.write("UINT32 nd_theme_accent(void) { return g_current.accent; }\n")
    out.write("UINT32 nd_theme_paper_top(UINT32 index) {\n")
    out.write("  const UINT32 (*papers)[2] = g_is_dark ? g_dark_papers : g_light_papers;\n")
    out.write("  UINT32 count = (UINT32)(sizeof(g_light_papers) / sizeof(g_light_papers[0]));\n\n")
    out.write("  return (index < count) ? papers[index][0] : papers[0][0];\n}\n")
    out.write("void nd_theme_set_accent(UINT32 rgb) {\n  g_accent = rgb & 0x00FFFFFFu;\n  theme_apply();\n}\n")
    out.write("UINT32 nd_theme_wallpaper(void) { return g_wallpaper; }\n")
    out.write("void nd_theme_set_wallpaper(UINT32 index) {\n")
    out.write("  if (index >= (UINT32)(sizeof(g_light_papers) / sizeof(g_light_papers[0]))) {\n    return;\n  }\n")
    out.write("  g_wallpaper = index;\n  theme_apply();\n}\n")
    out.write("int nd_theme_wallpaper_count(void) {\n")
    out.write("  return (int)(sizeof(g_light_papers) / sizeof(g_light_papers[0]));\n}")
    out.write("\n")
    return out.getvalue()


def gen_rust(doc):
    out = io.StringIO()
    out.write("//! Novus OS - design tokens (generated).\n")
    out.write("//!\n//! Generated by tools/themegen/themegen.py from theme.toml; edit the\n")
    out.write("//! TOML and regenerate, never this file.\n\n")
    out.write("#[derive(Clone, Copy)]\n")
    out.write("pub struct Palette {\n")
    for role in ROLES:
        out.write("    pub %s: u32,\n" % role)
    out.write("}\n\n")
    out.write("pub struct Metrics {\n")
    for m in METRICS:
        out.write("    pub %s: i16,\n" % m)
    out.write("}\n\n")
    out.write("pub static LIGHT: Palette = Palette {\n")
    for role in ROLES:
        out.write("    %s: %s,\n" % (role, rust_hex(doc["light"][role])))
    out.write("};\n\n")
    out.write("pub static DARK: Palette = Palette {\n")
    for role in ROLES:
        out.write("    %s: %s,\n" % (role, rust_hex(doc["dark"][role])))
    out.write("};\n\n")
    out.write("pub const METRICS: Metrics = Metrics {\n")
    for m in METRICS:
        out.write("    %s: %d,\n" % (m, int(doc["metrics"][m])))
    out.write("};\n\n")
    out.write("pub const MODE_LIGHT: u32 = 0;\n")
    out.write("pub const MODE_DARK: u32 = 1;\n")
    out.write("pub const MODE_AUTO: u32 = 2;\n")
    return out.getvalue()


def main():
    check = "--check" in sys.argv[1:]
    with open(SOURCE, "rb") as f:
        doc = tomllib.load(f)
    outputs = {
        OUT_C_H: gen_header(doc),
        OUT_C_C: gen_c(doc),
        OUT_RS: gen_rust(doc),
    }
    stale = []
    for path, text in outputs.items():
        old = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8", newline="") as f:
                old = f.read()
        if old != text:
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(text)
    if check:
        for path in stale:
            print("stale: " + os.path.relpath(path, ROOT))
        return 1 if stale else 0
    for path in outputs:
        print("wrote " + os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
