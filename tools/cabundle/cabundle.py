#!/usr/bin/env python3
"""Generate security/novu/cabundle.c from a set of trusted vendor roots.

The input is a PEM bundle that may contain many root certificates (the
repository's tools/cabundle/roots.pem is the production trust set, captured
from the Debian/Mozilla CA program). The generated C file holds one flat DER
blob plus an offset/length table, so the kernel can hold N trust anchors
without copying them into BSS.

Offline by design: Python stdlib only, no openssl, no network.

Usage:
  tools/cabundle/cabundle.py --pem tools/cabundle/roots.pem
  tools/cabundle/cabundle.py --pem tools/cabundle/roots.pem \
      --out security/novu/cabundle.c
  tools/cabundle/cabundle.py --empty            # reset to fail-closed
  tools/cabundle/cabundle.py --pem x.pem --der-only x.der
"""
import argparse
import base64
import sys

HEADER = """/**
 * Novus OS - update trust anchors (generated by tools/cabundle).
 * DO NOT EDIT BY HAND.
 *
 * %(what)s
 * %(how)s
 */
#include "cabundle.h"

"""

HEADER_PROD = """The production set contains real, self-signed, CA:TRUE vendor roots from
 * the Debian/Mozilla CA program, the curl CA bundle, ICANN and ISRG (see
 * tools/cabundle/roots.pem for the full source and license list; regenerate
 * with tools/cabundle/import_roots.py). The QEMU test anchor is NOT part of
 * this set; it is linked separately from security/novu/cabundle_e2e.c only
 * when E2E=1."""

HEADER_E2E = """QEMU-only test anchor, generated from tools/updatesrv/test_ca.pem.
 * Linked into the kernel ONLY when E2E=1. Never part of a production image.
 * The matching private key stays in tools/updatesrv/ and never enters the OS."""


def parse_pem(path):
    """Return a list of DER byte strings from a (possibly multi-cert) PEM."""
    der_list = []
    buf = []
    inside = False
    with open(path, "r", encoding="ascii", errors="ignore") as f:
        for line in f:
            s = line.strip()
            if s == "-----BEGIN CERTIFICATE-----":
                inside = True
                buf = []
                continue
            if s == "-----END CERTIFICATE-----":
                if inside and buf:
                    raw = base64.b64decode("".join(buf))
                    if raw and raw[0] == 0x30:
                        der_list.append(raw)
                inside = False
                buf = []
                continue
            if inside and s and not s.startswith("#"):
                buf.append(s)
    return der_list


def check_der(der):
    """Minimal DER SEQUENCE header check (definite, bounded length)."""
    if len(der) < 2 or der[0] != 0x30:
        return False
    b = der[1]
    if b < 0x80:
        body = b
        hdr = 2
    else:
        n = b & 0x7F
        if n == 0 or n > 4 or 2 + n > len(der):
            return False
        body = int.from_bytes(der[2:2 + n], "big")
        hdr = 2 + n
    return hdr + body == len(der)


def emit(ders, out, prefix="novus_cabundle"):
    blob = b"".join(ders)
    offs = []
    p = 0
    for d in ders:
        offs.append(p)
        p += len(d)
    n = len(ders)
    total = len(blob)

    prod = prefix == "novus_cabundle"
    what = HEADER_PROD if prod else HEADER_E2E
    how = ("Regenerate with tools/cabundle/import_roots.py (offline, pure"
           if prod else
           "Regenerate with tools/cabundle/cabundle.py (offline, pure")
    lines = [HEADER % {"what": what,
                       "how": how + " Python stdlib only)."}]
    lines.append("/* %d trust anchor(s), %d DER bytes */" % (n, total))
    lines.append("const UINT8 %s_der[%d] = {" % (prefix, max(1, total)))
    for i in range(0, total, 16):
        chunk = ", ".join("0x%02x" % b for b in blob[i:i + 16])
        lines.append("    " + chunk + ",")
    if total == 0:
        lines.append("    0x00,")
    lines.append("};")
    lines.append("const UINT32 %s_len = %du;" % (prefix, total))
    lines.append("const UINT32 %s_count = %du;" % (prefix, n))
    lines.append("const UINT32 %s_off[%d] = {" % (prefix, max(1, n)))
    for i in range(0, max(1, n), 8):
        chunk = ", ".join("%du" % v for v in offs[i:i + 8])
        lines.append("    " + chunk + ("," if i + 8 < n else ""))
    lines.append("};")
    lines.append("const UINT32 %s_root_len[%d] = {" % (prefix, max(1, n)))
    lens = [len(d) for d in ders]
    for i in range(0, max(1, n), 8):
        chunk = ", ".join("%du" % v for v in lens[i:i + 8])
        lines.append("    " + chunk + ("," if i + 8 < n else ""))
    lines.append("};")
    lines.append("")
    with open(out, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    return n, total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pem", default="", help="PEM bundle of root certificates")
    ap.add_argument("--der", default="", help="single DER root (legacy)")
    ap.add_argument("--empty", action="store_true", help="reset to fail-closed")
    ap.add_argument("--out", default="security/novu/cabundle.c")
    ap.add_argument("--der-only", default="", help="also write concatenated DER")
    ap.add_argument("--max", type=int, default=256, help="max roots allowed")
    ap.add_argument("--prefix", default="novus_cabundle",
                    help="C symbol prefix (novus_e2e_root for the test anchor)")
    args = ap.parse_args()

    if args.empty:
        ders = []
    elif args.pem:
        ders = parse_pem(args.pem)
    elif args.der:
        with open(args.der, "rb") as f:
            d = f.read()
        ders = [d] if d else []
    else:
        ap.error("one of --pem/--der/--empty is required")
        return 1

    for i, d in enumerate(ders):
        if not check_der(d):
            print("cabundle: cert #%d is not a well-formed DER SEQUENCE" % i,
                  file=sys.stderr)
            return 1
    if len(ders) > args.max:
        print("cabundle: %d roots exceeds --max %d" % (len(ders), args.max),
              file=sys.stderr)
        return 1

    if args.der_only:
        with open(args.der_only, "wb") as f:
            f.write(b"".join(ders))

    n, total = emit(ders, args.out, args.prefix)
    print("cabundle: %d root(s), %d DER bytes -> %s%s" % (
        n, total, args.out, " (fail-closed)" if n == 0 else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
