#!/usr/bin/env python3
"""Merge additional vendor roots into the production trust set.

All inputs are checked into the repository; nothing is downloaded here.

  Baseline : tools/cabundle/roots.pem      (Debian/Mozilla CA program)
  Upstream : user/ssl/certs/*.pem
               cacert.pem        - curl CA bundle, Mozilla root store (MPL-2.0)
               icannbundle.pem   - ICANN root CA bundle
               isrgrootx1.pem    - ISRG / Let's Encrypt root (RSA)
               isrg-root-x2.pem  - ISRG / Let's Encrypt root (EC)

Only *.pem files are trust inputs. Other files in that directory are download
artifacts: cacert.pem.sha256 is an integrity checksum, and curl_response holds
the DST Root CA X3 which expired on 2021-09-30. Both are deliberately ignored.

A candidate is accepted only when it is self-signed, CA:TRUE, not expired, and
not already in the set (deduplicated by SHA-256 over the DER). openssl is used
only here at import time; the kernel build itself stays offline and uses
cabundle.py, which is pure Python stdlib.

Usage:
  tools/cabundle/import_roots.py             # merge + regenerate cabundle.c
  tools/cabundle/import_roots.py --dry-run   # report candidates, write nothing
"""
import argparse
import base64
import hashlib
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cabundle  # noqa: E402  (same-directory module)

REPO = Path(__file__).resolve().parents[2]
BASE = REPO / "tools/cabundle/roots.pem"
UPSTREAM = REPO / "user/ssl/certs"
OUT_C = REPO / "security/novu/cabundle.c"

HEADER = """# Novus OS - trusted vendor root certificates
#
# Generated by tools/cabundle/import_roots.py from repository-local sources.
# Regenerate offline with:  python3 tools/cabundle/import_roots.py
#
# Sources and licenses:
#   * Debian ca-certificates bundle (/etc/ssl/certs/ca-certificates.crt),
#     derived from the Mozilla CA Certificate Program.
#     https://www.mozilla.org/en-US/about/governance/policies/security-group/certs/
#     Mozilla root store: MPL-2.0; Debian packaging: GPL-2.0+; each root
#     remains subject to the terms of its issuing CA. See
#     /usr/share/doc/ca-certificates/copyright.
#   * user/ssl/certs/cacert.pem - curl CA bundle, Mozilla root store as of
#     2026-11-05 (https://curl.se/docs/caextract.html, mk-ca-bundle.pl 1.35).
#     MPL-2.0. Integrity: user/ssl/certs/cacert.pem.sha256.
#   * user/ssl/certs/icannbundle.pem - ICANN root CA bundle (ICANN Root CA,
#     ICANN Root CA v2); subject to the ICANN Certification Authority CPS.
#   * user/ssl/certs/isrgrootx1.pem, isrg-root-x2.pem - ISRG / Let's Encrypt
#     roots; subject to the ISRG Certificate Policy. Both are already present
#     via the Debian/Mozilla baseline and are deduplicated away.
#
# Excluded: user/ssl/certs/curl_response (DST Root CA X3, expired 2021-09-30)
# and non-PEM artifacts. Only self-signed, CA:TRUE, unexpired roots are kept.
#
# Captured: 2026-11-14.  Count: %(count)d
#
# This file is checked into the repository. tools/cabundle/cabundle.py converts
# it (offline, no network, Python stdlib only) into security/novu/cabundle.c.
# Do not paste a private key here. The QEMU test anchor lives separately in
# tools/updatesrv/test_ca.pem and is NOT part of the production trust set.
"""


def as_pem(der):
    body = base64.encodebytes(der).decode("ascii")
    return ("-----BEGIN CERTIFICATE-----\n" + body +
            "-----END CERTIFICATE-----\n")


def validate(der):
    """Return (ok, reason). Host-side validation only, never in the OS image."""
    pem = as_pem(der).encode("ascii")
    expired = subprocess.run(
        ["openssl", "x509", "-noout", "-checkend", "0"],
        input=pem, capture_output=True)
    if expired.returncode != 0:
        return False, "expired or invalid validity"
    txt = subprocess.run(
        ["openssl", "x509", "-noout", "-subject", "-issuer", "-text"],
        input=pem, capture_output=True).stdout.decode("utf8", "ignore")
    subj = re.search(r"^subject=(.*)$", txt, re.M)
    iss = re.search(r"^issuer=(.*)$", txt, re.M)
    if not subj or not iss or subj.group(1).strip() != iss.group(1).strip():
        return False, "not self-signed"
    if "CA:TRUE" not in txt:
        return False, "not CA:TRUE"
    return True, "ok"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if not BASE.exists():
        print("missing baseline %s" % BASE, file=sys.stderr)
        return 1

    entries = []          # (der, source short tag)
    seen = set()

    def add_many(ders, tag):
        for d in ders:
            key = hashlib.sha256(d).hexdigest()
            if key in seen:
                continue
            seen.add(key)
            entries.append((d, tag))

    baseline = cabundle.parse_pem(str(BASE))
    add_many(baseline, "debian-mozilla")
    print("baseline roots: %d" % len(baseline))

    added, rejected, duplicate = [], [], 0
    for path in sorted(UPSTREAM.glob("*.pem")):
        ders = cabundle.parse_pem(str(path))
        for d in ders:
            key = hashlib.sha256(d).hexdigest()
            if key in seen:
                duplicate += 1
                continue
            if not cabundle.check_der(d):
                rejected.append((path.name, "malformed DER"))
                continue
            ok, why = validate(d)
            if not ok:
                rejected.append((path.name, why))
                continue
            seen.add(key)
            entries.append((d, path.name))
            added.append((path.name, key[:12]))

    print("upstream duplicates skipped: %d" % duplicate)
    print("rejected: %d %s" % (len(rejected), rejected if rejected else ""))
    print("new roots accepted: %d" % len(added))
    for name, key in added:
        print("  + %-24s %s" % (name, key))
    print("final trust set: %d roots, %d DER bytes" %
          (len(entries), sum(len(d) for d, _ in entries)))

    if len(entries) > 192:
        print("ERROR: exceeds NET_HTTP_MAX_ROOTS / NOVUS_CABUNDLE_MAX (192)",
              file=sys.stderr)
        return 1
    if args.dry_run:
        return 0

    lines = [HEADER % {"count": len(entries)}]
    for i, (der, tag) in enumerate(entries, 1):
        lines.append("# %03d  [%s]" % (i, tag))
        lines.append(as_pem(der).rstrip("\n"))
        lines.append("")
    BASE.write_text("\n".join(lines) + "\n", encoding="ascii")

    n, total = cabundle.emit([d for d, _ in entries], str(OUT_C),
                             prefix="novus_cabundle")
    print("wrote %s (%d roots, %d bytes) and %s" % (BASE, n, total, OUT_C))
    return 0


if __name__ == "__main__":
    sys.exit(main())
