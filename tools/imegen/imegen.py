#!/usr/bin/env python3
"""Novus OS - pinyin dictionary extractor and table generator.

Two jobs, one file:

  imegen.py --extract [TABLE]   turn the host's ibus pinyin table into the
                                compact, reviewable `pinyin.txt` next to this
                                script (committed; the build never needs the
                                host table again).
  imegen.py --gen               turn `pinyin.txt` into graphics/nd_ime_dict.c.

The shipped table is deliberately small: single-syllable input, at most a
handful of candidates per syllable, ordered by the frequency column of the
source table. That is enough for an IME that fits in a kernel image and
keeps the embedded glyph set in the low thousands.

Usage:
    python3 tools/imegen/imegen.py --extract
    python3 tools/imegen/imegen.py --gen
"""

import bz2
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PINYIN_TXT = os.path.join(HERE, "pinyin.txt")
OUT_C = os.path.join(ROOT, "graphics", "nd_ime_dict.c")

DEFAULT_TABLE = "/usr/share/ibus-table/data/pinyin_table.txt.bz2"

MAX_CANDIDATES = 6      # per syllable
MIN_FREQ = 300          # drop rare characters, they also cost a glyph

# Syllables we accept: the Hanyu Pinyin inventory, no tones. Anything else
# in the source table (rare readings, dialect) is skipped so a typed
# syllable always has candidates.
VOWELS = set("aeiouv")
INITIALS = {
    "", "b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j", "q", "x",
    "zh", "ch", "sh", "r", "z", "c", "s", "y", "w",
}


def is_syllable(s):
    if not s or len(s) > 6:
        return False
    if any(c not in "abcdefghijklmnopqrstuvwxyz" for c in s):
        return False
    if not any(c in VOWELS for c in s):
        return False
    for ini in INITIALS:
        if s.startswith(ini):
            return True
    return False


def strip_tone(py):
    return "".join(c for c in py if not c.isdigit()).lower()


def extract(table_path):
    text = bz2.open(table_path, "rb").read().decode("utf-8", "replace")
    best = {}  # syllable -> list of (freq, char)

    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        ch, readings, freq = parts[0], parts[1], parts[2]
        if len(ch) != 1:
            continue
        try:
            f = int(freq)
        except ValueError:
            continue
        # One character may have several readings; the first is the common
        # one and is enough for a single-syllable IME.
        syl = strip_tone(readings.split()[0])
        if not is_syllable(syl) or f < MIN_FREQ:
            continue
        best.setdefault(syl, []).append((f, ch))

    lines = []
    total_chars = 0
    for syl in sorted(best):
        items = sorted(best[syl], key=lambda t: -t[0])[:MAX_CANDIDATES]
        chars = "".join(c for _, c in items)
        lines.append(f"{syl}\t{chars}")
        total_chars += len(chars)

    header = [
        "# Novus IME dictionary: syllable <TAB> candidates, most frequent first.",
        "# Generated by tools/imegen/imegen.py --extract from ibus-table's",
        "# pinyin_table.txt (GPL, see that package). Committed on purpose:",
        "# the OS build must not need a host pinyin table.",
        f"# {len(lines)} syllables, {total_chars} candidate slots.",
    ]
    with open(PINYIN_TXT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(header + lines) + "\n")
    print(f"imegen: wrote {PINYIN_TXT} ({len(lines)} syllables, "
          f"{total_chars} slots)")


def gen_c():
    entries = []
    for line in open(PINYIN_TXT, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        syl, chars = line.split("\t")
        entries.append((syl, chars))

    # String pool for the syllables; candidates as a flat u32 array of
    # codepoints so the kernel needs no UTF-8 decoding at lookup time.
    pool = ""
    offsets = []
    for syl, _ in entries:
        offsets.append(len(pool))
        pool += syl + "\0"

    flat = []
    starts = []
    counts = []
    for _, chars in entries:
        starts.append(len(flat))
        for ch in chars:
            flat.append(ord(ch))
        counts.append(len(chars))

    out = []
    out.append("/**")
    out.append(" * Novus OS - pinyin dictionary (generated, do not edit).")
    out.append(" *")
    out.append(" * Source: tools/imegen/pinyin.txt, itself extracted from the")
    out.append(" * ibus-table pinyin table by tools/imegen/imegen.py.")
    out.append(" * Lookup is a binary search over the syllable table:")
    out.append(" * nd_ime_dict_lookup() in graphics/nd_ime.c.")
    out.append(" */")
    out.append("")
    out.append('#include "nd_internal.h"')
    out.append("#include \"nd_ime.h\"")
    out.append("")
    out.append(f"#define IME_STRLEN {len(pool) + 1}")
    out.append("")
    out.append("const char g_ime_pool[] = {")
    line = ""
    for ch in pool:
        if ch == "\0":
            line += "0, "
        else:
            esc = ch if ch != '"' and ch != "\\" else "\\" + ch
            line += f"'{esc}', "
        if len(line) > 90:
            out.append("    " + line.rstrip())
            line = ""
    if line:
        out.append("    " + line.rstrip())
    out.append("};")
    out.append("")
    out.append(f"const UINT16 g_ime_count = {len(entries)}u;")
    out.append("")
    out.append("const UINT16 g_ime_off[] = {")
    out.append("    " + ", ".join(str(v) for v in offsets) + ",")
    out.append("};")
    out.append("")
    out.append("const UINT16 g_ime_start[] = {")
    out.append("    " + ", ".join(str(v) for v in starts) + ",")
    out.append("};")
    out.append("")
    out.append("const UINT8 g_ime_len[] = {")
    out.append("    " + ", ".join(str(v) for v in counts) + ",")
    out.append("};")
    out.append("")
    out.append("const UINT32 g_ime_cand[] = {")
    for i in range(0, len(flat), 8):
        out.append("    " + ", ".join(f"0x{c:04X}u" for c in flat[i:i + 8]) + ",")
    out.append("};")
    out.append("")

    with open(OUT_C, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"imegen: wrote {OUT_C} ({len(entries)} syllables, {len(flat)} chars)")


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == "--extract":
        table = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_TABLE
        if not os.path.exists(table):
            sys.exit(f"pinyin table not found: {table}")
        extract(table)
    elif len(sys.argv) >= 2 and sys.argv[1] == "--gen":
        gen_c()
    else:
        sys.exit(__doc__)


main()
