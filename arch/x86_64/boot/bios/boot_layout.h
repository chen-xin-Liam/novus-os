#define BIOS_DAP_ADDR 0x6000
#define BIOS_BOOT_DRIVE_ADDR (BIOS_DAP_ADDR + 0x10)
#define BIOS_DISK_BOUNCE 0x30000
#define BIOS_PAGE_TABLES 0x20000
#define BIOS_BOOT_INFO 0x50000
#define BIOS_E820_BUFFER 0x50100
#define BIOS_E820_MAX_ENTRIES 128
#define BIOS_VBE_CONTROL 0x51000
#define BIOS_VBE_MODE_INFO 0x51200
#define BIOS_EFI_MMAP 0x53000
#define BIOS_EFI_MMAP_CAPACITY 512
#define BIOS_LONG_STACK_TOP 0x7E000
#define BIOS_KERNEL_CHUNK_SECTORS 64

#define BIOS_BOOT_INFO_MAGIC 0x3142564E
#define BIOS_BOOT_INFO_VERSION 1
#define BIOS_BI_E820_COUNT 8
#define BIOS_BI_E820_ENTRY_SIZE 12
#define BIOS_BI_E820_ADDR 16
#define BIOS_BI_VBE_AVAILABLE 24
#define BIOS_BI_WIDTH 28
#define BIOS_BI_HEIGHT 32
#define BIOS_BI_PITCH_BYTES 36
#define BIOS_BI_BPP 40
#define BIOS_BI_RED_SIZE 42
#define BIOS_BI_RED_POS 43
#define BIOS_BI_GREEN_SIZE 44
#define BIOS_BI_GREEN_POS 45
#define BIOS_BI_BLUE_SIZE 46
#define BIOS_BI_BLUE_POS 47
#define BIOS_BI_FB_BASE 48
#define BIOS_BI_FB_SIZE 56
#define BIOS_BI_VBE_MODE 64

#define STAGE2_ADDR(symbol) (STAGE2_LOAD + ((symbol) - stage2_entry))

#endif